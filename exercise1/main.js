let x = 7;
let y = 3;

console.log("Addition:", x + y);          // Addition: 7 + 3 = 10
console.log("Subtraction:", x - y);       // Subtraction: 7 - 3 = 4
console.log("Multiplication:", x * y);    // Multiplication: 7 * 3 = 21
console.log("Division:", x / y);          // Division: 7 / 3 = 2.3333...
console.log("Modulus:", x % y);           // Modulus: 7 % 3 = 1 (remainder)
console.log("Exponentiation:", x ** y);   // Exponentiation: 7 raised to the power of 3 = 343

// Increment and Decrement
console.log("Pre-increment x:", ++x);     // Pre-increment: x becomes 8 before printing
console.log("Post-increment x:", x++);    // Post-increment: x is printed (8) then incremented
console.log("printing x of Post-increment:", x);

console.log("Pre-decrement y:", --y);     // Pre-decrement: y becomes 2 before printing
console.log("Post-decrement y:", y--);    // Post-decrement: y is printed (2) then decremented
console.log("printing y of Post-decrement: ",y); // printing y of Post-decrement:  1


